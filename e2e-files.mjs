// Real Chrome: upload a real .xlsx, then backup + restore through the page.
import { spawn } from 'node:child_process';
import fs from 'node:fs';
const port = 9555;
const ch = spawn('google-chrome', ['--headless=new','--no-sandbox','--disable-gpu',`--remote-debugging-port=${port}`,'--user-data-dir=/tmp/cp-files','about:blank'],{stdio:'ignore'});
await new Promise(r=>setTimeout(r,2500));
const tabs = await (await fetch(`http://127.0.0.1:${port}/json`)).json();
const ws = new WebSocket(tabs.find(t=>t.type==='page').webSocketDebuggerUrl);
await new Promise(r=>ws.onopen=r);
let id=0; const pend=new Map();
ws.onmessage=e=>{const m=JSON.parse(e.data); if(m.id&&pend.has(m.id)){pend.get(m.id)(m);pend.delete(m.id);}};
const send=(method,params={})=>new Promise(r=>{const i=++id;pend.set(i,r);ws.send(JSON.stringify({id:i,method,params}));});
const ev=async(x)=>{const r=await send('Runtime.evaluate',{expression:x,returnByValue:true,awaitPromise:true}); if(r.result.exceptionDetails) throw new Error(JSON.stringify(r.result.exceptionDetails)); return r.result.result.value;};
const sleep=ms=>new Promise(r=>setTimeout(r,ms));
let fails=0; const ok=(c,m)=>{console.log((c?'PASS ':'FAIL ')+m); if(!c) fails++;};
await send('Page.enable'); await send('DOM.enable');
await send('Page.navigate',{url:`file://${process.cwd()}/app.html`}); await sleep(700);
await ev(`localStorage.clear()`); await send('Page.navigate',{url:`file://${process.cwd()}/app.html`}); await sleep(700);
const doc=(await send('DOM.getDocument')).result.root.nodeId;
const q=async(s)=>(await send('DOM.querySelector',{nodeId:doc,selector:s})).result.nodeId;
const xlsx=fs.existsSync('/tmp/sample.xlsx')?'/tmp/sample.xlsx':'/downloads/maead-sample.xlsx';
await send('DOM.setFileInputFiles',{nodeId:await q('#file'),files:[xlsx]}); await sleep(1200);
const info=await ev(`document.getElementById('parseInfo').textContent`);
ok(/اتفتح ملف إكسل/.test(info)&&/اتقرا 3 ميعاد/.test(info),'xlsx opened in the browser, 3 rows: '+info.slice(0,60));
const name=await ev(`document.getElementById('paste').value.split('\\n')[1]`);
ok(/منى/.test(name)&&/01000000001/.test(name),'phone stored as a number got its leading 0');
// mark one sent, backup, clear, restore
await ev(`document.getElementById('day').value='2026-11-27';document.getElementById('day').dispatchEvent(new Event('change'))`);
await ev(`document.querySelector('#list select')&&(document.querySelector('#list select').value='came',document.querySelector('#list select').dispatchEvent(new Event('change',{bubbles:true})))`);
const snap=await ev(`localStorage.getItem('maead.v1')`);
const backup=await ev(`(()=>{return Maead.makeBackup(JSON.parse(localStorage.getItem('maead.v1')),'t')})()`);
fs.writeFileSync('/tmp/backup.json',backup);
await ev(`document.getElementById('btnClear').click()`); await sleep(200);
ok(await ev(`JSON.parse(localStorage.getItem('maead.v1')).text===''`),'cleared');
await ev(`window.confirm=()=>true`);
await send('DOM.setFileInputFiles',{nodeId:await q('#restoreFile'),files:['/tmp/backup.json']}); await sleep(600);
ok(/اترجّعت النسخة \(3 ميعاد\)/.test(await ev(`document.getElementById('backupInfo').textContent`)),'restore brings back 3 rows');
ok(await ev(`JSON.parse(localStorage.getItem('maead.v1')).text===${JSON.stringify(JSON.parse(snap).text)}`),'restored data equals the original');
fs.writeFileSync('/tmp/bad.json','{"hello":1}');
await send('DOM.setFileInputFiles',{nodeId:await q('#restoreFile'),files:['/tmp/bad.json']}); await sleep(400);
ok(/مش نسخة احتياطية/.test(await ev(`document.getElementById('backupInfo').textContent`)),'a foreign file is refused with a clear message');
ws.close(); ch.kill(); console.log(fails?`${fails} FAILED`:'ALL FILE CHECKS PASSED'); process.exit(fails?1:0);
